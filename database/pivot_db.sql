CREATE DATABASE IF NOT EXISTS pivot_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pivot_db;
CREATE TABLE IF NOT EXISTS users (id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_login TIMESTAMP NULL DEFAULT NULL,
 PRIMARY KEY(id), UNIQUE KEY uq_users_email(email)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS user_profiles (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 user_id BIGINT UNSIGNED NOT NULL,
 headline VARCHAR(180) NULL,
 target_role VARCHAR(120) NULL,
 location VARCHAR(120) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), UNIQUE KEY uq_profiles_user(user_id),
 CONSTRAINT fk_profiles_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS skills (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 skill_name VARCHAR(100) NOT NULL,
 PRIMARY KEY(id), UNIQUE KEY uq_skills_name(skill_name)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS user_skills (
 user_id BIGINT UNSIGNED NOT NULL, skill_id BIGINT UNSIGNED NOT NULL,
 proficiency TINYINT UNSIGNED NOT NULL DEFAULT 0, is_verified BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(user_id,skill_id),
 CONSTRAINT fk_user_skills_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_user_skills_skill FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS learning_progress (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, user_id BIGINT UNSIGNED NOT NULL,
 course_title VARCHAR(180) NOT NULL, completed_lessons INT UNSIGNED NOT NULL DEFAULT 0,
 total_lessons INT UNSIGNED NOT NULL DEFAULT 0,
 status ENUM('not_started','in_progress','completed') NOT NULL DEFAULT 'not_started',
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), KEY idx_learning_user(user_id),
 CONSTRAINT fk_learning_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
